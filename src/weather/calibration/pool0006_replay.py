class ReplayError(RuntimeError):
    pass


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def repo_root():
    return Path(__file__).resolve().parents[3]


def check_out_dir(out_dir, root=None):
    out = Path(out_dir).resolve()
    base = Path(root if root is not None else OUT_ROOT).resolve()
    if base not in out.parents:
        raise ReplayError(f"refusing to write outside {base}: {out}")
    if out.exists():
        raise ReplayError(f"refusing to overwrite an existing output directory {out}")
    return out


def check_pins(member, root=None, members=MEMBERS, code_pins=CODE_PINS):
    """Every recorded input and the member's code must match its pin; returns {name: sha}."""
    if member not in members:
        raise ReplayError(f"unknown member {member!r}; POOL-0006 members are {sorted(members)}")
    root = Path(root or repo_root())
    got = {}
    for rel, pin in code_pins.items():
        sha = _sha(root / rel)
        if sha != pin:
            raise ReplayError(f"{rel} sha256 {sha} is not the recorded {pin}")
        got[rel] = sha
    for key in ("rule", "nowcasts", "p1", "p2", "gate1", "recorded"):
        path, pin = members[member][key]
        if not Path(path).is_file():
            raise ReplayError(f"{member} {key} missing: {path}")
        sha = _sha(path)
        if sha != pin:
            raise ReplayError(f"{member} {key} {path} sha256 {sha} is not the pin {pin}")
        got[key] = sha
    return got


def headline(payload):
    prim = payload["gate2"]["primary"]
    return {"estimate": prim["estimate"], "ci95": list(prim["ci95"])}


def c4_compare(replay, recorded, tol=C4_TOL):
    """C4: the replayed primary dR estimate and 95% bounds within ``tol`` of the recorded ones."""
    a, b = headline(replay), headline(recorded)
    pairs = [("estimate", a["estimate"], b["estimate"]), ("ci95_lo", a["ci95"][0], b["ci95"][0]),
             ("ci95_hi", a["ci95"][1], b["ci95"][1])]
    diffs = {}
    for name, x, y in pairs:
        if x is None or y is None or not (math.isfinite(x) and math.isfinite(y)):
            diffs[name] = None
        else:
            diffs[name] = abs(float(x) - float(y))
    ok = all(d is not None and d <= tol for d in diffs.values())
    return {"replay": a, "recorded": b, "abs_diff": diffs, "tolerance": tol, "pass": bool(ok)}


class FrameCapture:
    """Wraps ``dev_scorecard_data.module_predictions`` for one call and keeps its return value unchanged."""

    def __init__(self, data_module):
        self.data = data_module
        self.frames = []
        self._orig = None

    def __enter__(self):
        self._orig = self.data.module_predictions
        orig = self._orig

        def capture(*args, **kwargs):
            frame, meta = orig(*args, **kwargs)
            self.frames.append(frame.copy())
            return frame, meta

        self.data.module_predictions = capture
        return self

    def __exit__(self, *exc):
        self.data.module_predictions = self._orig
        return False

    def frame(self):
        if len(self.frames) != 1:
            raise ReplayError(f"gate 2 called module_predictions {len(self.frames)} times; expected once")
        return self.frames[0]


def write_emit(frame, path):
    """Write the captured frame as parquet, sorted, and re-read it bitwise; returns (sha256, n rows)."""
    import numpy as np
    import pandas as pd

    cols = ["row_key", "band_index", "p"]
    f = frame[cols].sort_values(["row_key", "band_index"], kind="mergesort").reset_index(drop=True)
    if f.duplicated(["row_key", "band_index"]).any():
        raise ReplayError("candidate frame repeats a (row_key, band_index)")
    f.to_parquet(path, index=False)
    back = pd.read_parquet(path)
    same = (list(back.columns) == cols and len(back) == len(f)
            and np.array_equal(back.row_key.astype(str).to_numpy(), f.row_key.astype(str).to_numpy())
            and np.array_equal(back.band_index.to_numpy(), f.band_index.to_numpy())
            and np.array_equal(back.p.to_numpy(float), f.p.to_numpy(float)))
    if not same:
        raise ReplayError("emit parquet does not re-read bitwise")
    return _sha(path), int(len(f))


def git_tree(root):
    proc = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD^{tree}"], capture_output=True, text=True,
                          timeout=60, check=False)
    return proc.stdout.strip() if proc.returncode == 0 else None


def loaded_files(root, modules=None):
    """sha256 of every loaded module file inside the run tree (the run env as executed)."""
    root = Path(root).resolve()
    out = {}
    for mod in list((modules if modules is not None else sys.modules).values()):
        f = getattr(mod, "__file__", None)
        if not f:
            continue
        p = Path(f).resolve()
        if root in p.parents:
            out[p.relative_to(root).as_posix()] = _sha(p)
    return dict(sorted(out.items()))


def _write_json(path, payload):
    if path.exists():
        raise ReplayError(f"refusing to overwrite {path}")
    path.write_text(json.dumps(payload, indent=1, sort_keys=True, default=str), encoding="utf-8")
    return path


