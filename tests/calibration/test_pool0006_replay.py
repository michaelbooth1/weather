"""POOL-0006 member replay harness and C4 gate (lane L17, 2026-10-31; ledger row 94, Clarification 1).

Synthetic frames and fake gate 2 payloads only; no real rows, no layout.
Guards: Clarification 1 section 1 - a member emit is regenerated by replaying the member's own gate 2 and is
written only after C4 (the replayed primary dR estimate and 95% bounds within 1e-9 of the recorded receipt);
a failing member writes a C4 receipt with no emit. The captured frame is exactly the one gate 2 scored (one
module_predictions call, returned unchanged, wrapper restored) and the emit re-reads bitwise. Input and code
pins refuse on any mismatch; the out dir is write-once below C:/t/l17/pool/c4.
"""
import hashlib
import importlib
import json
import types
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

rp = importlib.import_module("weather.calibration.pool0006_replay")
ROOT = Path(__file__).resolve().parents[2]


def _payload(est=-0.023170310481208888, lo=-0.05200948542013499, hi=0.004703930752723948):
    return {"label": "toy", "gate2": {"primary": {"estimate": est, "ci95": [lo, hi]}},
            "inputs": {"layout_manifest_sha256": rp.LAYOUT_MANIFEST_SHA256}}


def _frame():
    return pd.DataFrame({"row_key": ["b", "a", "a", "b"], "band_index": [1, 1, 0, 0], "p": [0.25, 0.6, 0.4, 0.75]})


def test_code_pins_match_this_tree():
    for rel, pin in rp.CODE_PINS.items():
        assert hashlib.sha256((ROOT / rel).read_bytes()).hexdigest() == pin, rel


def test_out_dir_is_write_once_below_the_root(tmp_path):
    root = tmp_path / "c4"
    assert rp.check_out_dir(root / "rpd", root) == (root / "rpd").resolve()
    with pytest.raises(rp.ReplayError):
        rp.check_out_dir(tmp_path / "elsewhere", root)
    (root / "old").mkdir(parents=True)
    with pytest.raises(rp.ReplayError):
        rp.check_out_dir(root / "old", root)


def test_pins_refuse_any_mismatch_and_unknown_members(tmp_path):
    files = {}
    for key in ("rule", "nowcasts", "p1", "p2", "gate1", "recorded"):
        f = tmp_path / f"{key}.bin"
        f.write_bytes(key.encode())
        files[key] = (str(f), hashlib.sha256(key.encode()).hexdigest())
    code = tmp_path / "tree" / "m.py"
    code.parent.mkdir()
    code.write_bytes(b"x = 1\n")
    pins = {"m.py": hashlib.sha256(b"x = 1\n").hexdigest()}
    members = {"R-PD": files}
    got = rp.check_pins("R-PD", tmp_path / "tree", members, pins)
    assert set(got) == {"m.py", "rule", "nowcasts", "p1", "p2", "gate1", "recorded"}
    with pytest.raises(rp.ReplayError):
        rp.check_pins("X17", tmp_path / "tree", members, pins)
    (tmp_path / "gate1.bin").write_bytes(b"changed")
    with pytest.raises(rp.ReplayError):
        rp.check_pins("R-PD", tmp_path / "tree", members, pins)
    (tmp_path / "gate1.bin").write_bytes(b"gate1")
    code.write_bytes(b"x = 2\n")
    with pytest.raises(rp.ReplayError):
        rp.check_pins("R-PD", tmp_path / "tree", members, pins)


def test_c4_passes_within_1e9_and_fails_beyond_or_on_missing():
    rec = _payload()
    assert rp.c4_compare(_payload(est=-0.023170310481208888 + 5e-10), rec)["pass"]
    assert not rp.c4_compare(_payload(est=-0.023170310481208888 + 2e-9), rec)["pass"]
    assert not rp.c4_compare(_payload(hi=0.004703930752723948 - 2e-9), rec)["pass"]
    assert not rp.c4_compare(_payload(lo=None), rec)["pass"]
    assert rp.c4_compare(_payload(), rec)["abs_diff"] == {"estimate": 0.0, "ci95_lo": 0.0, "ci95_hi": 0.0}


def test_frame_capture_returns_the_frame_unchanged_once_and_restores():
    fr = _frame()
    data = types.SimpleNamespace(module_predictions=lambda spec, lay, folds: (fr, {"name": "toy"}))
    orig = data.module_predictions
    with rp.FrameCapture(data) as cap:
        out, meta = data.module_predictions(None, None, None)
        assert out is fr and meta == {"name": "toy"}
    assert data.module_predictions is orig
    pd.testing.assert_frame_equal(cap.frame(), fr)
    with rp.FrameCapture(data) as cap0:
        pass
    with pytest.raises(rp.ReplayError):
        cap0.frame()
    with rp.FrameCapture(data) as cap2:
        data.module_predictions(None, None, None)
        data.module_predictions(None, None, None)
    with pytest.raises(rp.ReplayError):
        cap2.frame()


def test_emit_is_sorted_and_rereads_bitwise_and_refuses_duplicates(tmp_path):
    sha, n = rp.write_emit(_frame(), tmp_path / "e.parquet")
    back = pd.read_parquet(tmp_path / "e.parquet")
    assert n == 4 and sha == hashlib.sha256((tmp_path / "e.parquet").read_bytes()).hexdigest()
    assert list(back.row_key) == ["a", "a", "b", "b"] and list(back.band_index) == [0, 1, 0, 1]
    assert np.array_equal(back.p.to_numpy(), [0.4, 0.6, 0.75, 0.25])
    dup = pd.concat([_frame(), _frame().iloc[:1]], ignore_index=True)
    with pytest.raises(rp.ReplayError):
        rp.write_emit(dup, tmp_path / "d.parquet")


def _fake_run(tmp_path, monkeypatch, replay_est):
    import weather.calibration.predawn_0006 as pd0
    from weather.reporting.scorecards import dev_scorecard as sc
    from weather.reporting.scorecards import dev_scorecard_data as data

    recorded = tmp_path / "gate2.json"
    recorded.write_text(json.dumps(_payload()), encoding="utf-8")
    member = {k: (str(recorded), "x") for k in ("rule", "nowcasts", "p1", "p2", "gate1", "recorded")}
    member.update(rule_const="RULE_PD_SHA256", second_precondition="P2")
    monkeypatch.setattr(rp, "MEMBERS", {"R-PD": member})
    monkeypatch.setattr(rp, "check_pins", lambda m, root=None: {"ok": "1"})
    monkeypatch.setattr(rp, "OUT_ROOT", tmp_path / "c4")
    monkeypatch.setattr(sc, "code_sha256", lambda: rp.SCORECARD_CODE_SHA256)
    monkeypatch.setattr(data, "module_predictions", lambda spec, lay, folds: (_frame(), {}))
    seen = {}

    def fake_gate2(**kw):
        seen.update(kw)
        frame, _ = data.module_predictions(None, None, None)
        assert len(frame) == 4
        Path(kw["out_path"]).write_text("{}", encoding="utf-8")
        return _payload(est=replay_est)

    monkeypatch.setattr(pd0, "gate2", fake_gate2)
    rec = rp.run(member="R-PD", out_dir=tmp_path / "c4" / "rpd")
    assert seen["pinned"] == pd0.RULE_PD_SHA256 and seen["second_precondition"] == "P2"
    assert seen["label"] == "toy"
    return rec


def test_run_writes_the_emit_only_after_c4_passes(tmp_path, monkeypatch):
    rec = _fake_run(tmp_path, monkeypatch, -0.023170310481208888)
    out = tmp_path / "c4" / "rpd"
    assert rec["c4"]["pass"] and rec["emit"]["rows"] == 4
    assert rec["emit"]["sha256"] == hashlib.sha256((out / "emit_R-PD.parquet").read_bytes()).hexdigest()
    assert json.loads((out / "c4_R-PD.json").read_text(encoding="utf-8"))["c4"]["pass"] is True


def test_run_drops_a_member_that_fails_c4(tmp_path, monkeypatch):
    rec = _fake_run(tmp_path, monkeypatch, -0.0232)
    out = tmp_path / "c4" / "rpd"
    assert not rec["c4"]["pass"] and rec["emit"] is None
    assert not (out / "emit_R-PD.parquet").exists()
    assert json.loads((out / "c4_R-PD.json").read_text(encoding="utf-8"))["c4"]["pass"] is False
